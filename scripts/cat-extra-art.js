/* New stories reuse Mikan's established face library; no scaled/rotated cats. */
module.exports=function({art,stage,leg}){
  for(let i=0;i<3;i++)stage('knead_body_'+i,c=>{
    c.poly([[13,17],[19,17],[21,20],[22,24],[22,26],[20,27],[12,27],[10,25],[12,21]],'f');
    c.inside(k=>k.poly([[13,18],[18,18],[19,21],[17,25],[13,25],[12,22]],'c').r(20,21,2,1,'s').p(11,24,'s').p(18,25,'b'));
    if(i===1)c.p(12,25,'b');if(i===2)c.p(19,25,'b');c.outline();
  });
  const knead=[[[[14,22],[13,24],[12,25]],[[19,22],[20,24],[20,25]]],
    [[[14,22],[13,25],[12,27]],[[19,22],[20,23],[20,24]]],
    [[[14,22],[13,23],[12,24]],[[19,22],[20,25],[20,27]]],
    [[[14,22],[13,24],[12,26]],[[19,22],[20,24],[20,26]]]];
  knead.forEach((paws,i)=>stage('knead_paws_'+i,c=>paws.forEach(p=>leg(c,p,true,true))));
  for(let i=0;i<3;i++)stage('cushion_'+i,c=>{
    c.poly([[7,25],[11,24],[23,24],[27,26],[26,29],[23,30],[8,30],[5,28]],'g');
    c.inside(k=>k.poly([[8,25],[13,25+(i===1?1:0)],[20,25+(i===2?1:0)],[25,26],[24,28],[8,28]],'t').r(9,29,14,1,'v').p(7,28,'t').p(25,28,'t')).outline();
  });
  stage('box_back',c=>{
    c.poly([[5,21],[9,18],[25,18],[28,21],[27,29],[5,29]],'b');
    c.inside(k=>k.poly([[7,21],[11,20],[24,20],[26,21],[24,25],[8,25]],'d')).outline();
  });
  for(let i=0;i<3;i++)stage('box_front_'+i,c=>{
    c.poly([[5,23],[27,23],[27,29],[24,30],[6,30]],'b');
    c.inside(k=>k.r(7,24,16,4,'h').r(23,24,3,5,'s').r(15,24,3,6,'c')).outline();
    c.poly([[5,22],[3,i===1?19:21],[1,23],[5,25],[10,23]],'b').outline();
    c.poly([[26,22],[29,i===2?19:21],[30,23],[27,25],[23,23]],'b').outline();
    c.r(8,26,4,2,'d').p(12,25,'d').p(12,28,'d').p(9,26,'h');
  });
  for(let i=0;i<3;i++)stage('reach_body_'+i,c=>{
    const top=17-i*2;
    c.poly([[13,top],[19,top],[21,top+3],[21,24],[23,27],[21,28],[11,28],[10,26],[12,22]],'f');
    c.inside(k=>k.poly([[13,top+1],[18,top+1],[19,top+4],[17,25],[13,25],[12,22]],'c').r(20,21,2,1,'s').r(12,26,3,2,'c').r(18,26,3,2,'c').p(15,27,'b').p(17,27,'b')).outline();
  });
  const reaches=[[[12,21],[9,19],[8,17]],[[12,19],[8,15],[6,11]],[[12,19],[8,17],[5,15]],[[12,22],[10,24],[9,26]]];
  reaches.forEach((p,i)=>stage('reach_paw_'+i,c=>leg(c,p,true,true)));
  art('leaf_0',7,6,c=>c.poly([[1,4],[2,1],[6,0],[6,3],[3,5]],'g').path([[0,5],[3,3],[5,1]],'v').p(4,1,'t').p(5,2,'t'));
  art('leaf_1',6,7,c=>c.poly([[3,0],[5,3],[4,6],[1,5],[1,2]],'y').path([[3,1],[3,4],[1,6]],'s').p(4,3,'h'));
  art('leaf_2',7,5,c=>c.poly([[0,2],[3,0],[6,1],[5,3],[2,4]],'g').path([[0,3],[3,2],[6,1]],'v').p(3,1,'t').p(4,1,'t'));
  const swats=[[[21,23],[24,22],[25,20]],[[21,21],[25,18],[27,15]],[[21,23],[25,24],[27,26]],[[21,23],[23,25],[22,27]]];
  swats.forEach((p,i)=>stage('bug_paw_'+i,c=>leg(c,p,true,true)));
  for(let i=0;i<2;i++)art('tiny_fly_'+i,4,4,c=>c.p(1,1,'v').p(2,2,'v').p(0,i?1:0,'u').p(3,i?1:0,'u').p(1,3,'s').p(2,3,'s'));
};
